import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'
import { getServerUser } from '@/lib/get-server-user'
import { getEffectivePermissions } from '@/lib/permission-utils'
import { emitNotification } from '@/lib/notifications/notification-emitter'

/**
 * POST /api/expense-account/outgoing-loans/[loanId]/repayment-requests/[paymentId]/approve
 * Cashier approves a pending repayment request — this is where the money
 * actually moves (debit the repaying business, credit the lender, reduce
 * the loan's outstanding balance). Mirrors the money-movement logic the
 * direct-record /payments route already has, just moved to fire here
 * instead of at request time.
 */
export async function POST(
  request: NextRequest,
  { params }: { params: { loanId: string; paymentId: string } }
) {
  try {
    const user = await getServerUser()
    if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

    const permissions = getEffectivePermissions(user)
    if (!permissions.canManageLending && user.role !== 'admin') {
      return NextResponse.json({ error: 'Permission denied — canManageLending required' }, { status: 403 })
    }

    const loan = await prisma.accountOutgoingLoans.findUnique({
      where: { id: params.loanId },
      include: {
        recipientPerson: { select: { fullName: true } },
        recipientBusiness: { select: { name: true } },
        recipientEmployee: { select: { fullName: true } },
        expenseAccount: { select: { businessId: true } },
      },
    })
    if (!loan) return NextResponse.json({ error: 'Loan not found' }, { status: 404 })
    if (loan.status !== 'ACTIVE') {
      return NextResponse.json({ error: `Cannot approve a repayment for a loan in status: ${loan.status}` }, { status: 400 })
    }

    const pending = await prisma.accountOutgoingLoanPayments.findUnique({ where: { id: params.paymentId } })
    if (!pending || pending.loanId !== loan.id) {
      return NextResponse.json({ error: 'Repayment request not found' }, { status: 404 })
    }
    if (pending.status !== 'PENDING') {
      return NextResponse.json({ error: `Cannot approve a repayment request in status: ${pending.status}` }, { status: 400 })
    }

    const repayAmount = Number(pending.amount)
    const remaining = Number(loan.remainingBalance)
    if (repayAmount > remaining + 0.001) {
      return NextResponse.json({
        error: `Repayment exceeds outstanding balance of $${remaining.toFixed(2)}`,
      }, { status: 400 })
    }

    const recipientName = loan.recipientPerson?.fullName ?? loan.recipientBusiness?.name ?? loan.recipientEmployee?.fullName ?? 'Unknown'
    const newBalance = Math.max(0, remaining - repayAmount)
    const isFullyPaid = newBalance <= 0.001

    await prisma.$transaction(async (tx: any) => {
      // Credit the lender's expense account
      const deposit = await tx.expenseAccountDeposits.create({
        data: {
          expenseAccountId: loan.expenseAccountId!,
          sourceType: 'LOAN_REPAYMENT',
          sourceOutgoingLoanId: loan.id,
          amount: repayAmount,
          depositDate: pending.paymentDate,
          autoGeneratedNote: `📥 Loan repayment from ${recipientName} — ${loan.loanNumber}`,
          manualNote: pending.notes,
          createdBy: user.id,
        },
      })
      await tx.expenseAccounts.update({
        where: { id: loan.expenseAccountId! },
        data: { balance: { increment: repayAmount } },
      })

      // Real cash/EcoCash physically received — needs its own pool inflow
      const loanBusinessId = loan.expenseAccount?.businessId ?? null
      if (loanBusinessId && (pending.paymentMethod === 'CASH' || pending.paymentMethod === 'ECOCASH')) {
        await tx.cashBucketEntry.create({
          data: {
            businessId: loanBusinessId,
            entryType: 'LOAN_REPAYMENT',
            direction: 'INFLOW',
            amount: repayAmount,
            paymentChannel: pending.paymentMethod,
            referenceType: 'LOAN_REPAYMENT',
            referenceId: deposit.id,
            notes: `Loan repayment received from ${recipientName} — ${loan.loanNumber}`,
            entryDate: pending.paymentDate,
            createdBy: user.id,
          },
        })
      }

      // Debit the borrower's primary expense account
      if (loan.loanType === 'BUSINESS' && loan.recipientBusinessId) {
        const borrowerAccount = await tx.expenseAccounts.findFirst({
          where: { businessId: loan.recipientBusinessId, isActive: true, isSibling: false },
          orderBy: { createdAt: 'asc' },
          select: { id: true },
        })
        if (borrowerAccount) {
          await tx.expenseAccountPayments.create({
            data: {
              expenseAccountId: borrowerAccount.id,
              payeeType: 'NONE',
              amount: repayAmount,
              paymentDate: pending.paymentDate,
              paymentType: 'LOAN_REPAYMENT',
              notes: pending.notes ?? `💸 Loan repayment — ${loan.loanNumber}`,
              status: 'SUBMITTED',
              createdBy: user.id,
            },
          })
          await tx.expenseAccounts.update({
            where: { id: borrowerAccount.id },
            data: { balance: { decrement: repayAmount } },
          })
        }
      }

      await tx.accountOutgoingLoanPayments.update({
        where: { id: pending.id },
        data: {
          status: 'APPROVED',
          depositId: deposit.id,
          approvedBy: user.id,
          approvedAt: new Date(),
        },
      })

      await tx.accountOutgoingLoans.update({
        where: { id: loan.id },
        data: {
          remainingBalance: newBalance,
          status: isFullyPaid ? 'PAID_OFF' : 'ACTIVE',
        },
      })
    })

    try {
      await emitNotification({
        userIds: [pending.recordedBy],
        type: 'LOAN_REPAYMENT_APPROVED',
        title: 'Loan repayment approved',
        message: isFullyPaid
          ? `${loan.loanNumber} fully repaid — loan closed`
          : `${loan.loanNumber} — $${repayAmount.toFixed(2)} repayment approved, $${newBalance.toFixed(2)} remaining`,
        linkUrl: `/expense-accounts/${loan.expenseAccountId}?tab=lent-out`,
        metadata: { loanId: loan.id, loanNumber: loan.loanNumber },
      })
    } catch { /* non-critical */ }

    return NextResponse.json({
      success: true,
      data: {
        message: isFullyPaid ? 'Loan fully repaid and marked as Paid Off' : `Repayment approved. Remaining: $${newBalance.toFixed(2)}`,
        remainingBalance: newBalance,
        status: isFullyPaid ? 'PAID_OFF' : 'ACTIVE',
      },
    })
  } catch (error) {
    console.error('Error approving repayment request:', error)
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 })
  }
}
