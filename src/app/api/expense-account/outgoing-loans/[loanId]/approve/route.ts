import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'
import { getServerUser } from '@/lib/get-server-user'
import { getEffectivePermissions } from '@/lib/permission-utils'
import { emitNotification } from '@/lib/notifications/notification-emitter'

/**
 * POST /api/expense-account/outgoing-loans/[loanId]/approve
 * EMPLOYEE loans: moves PENDING_APPROVAL → PENDING_CONTRACT (checks payroll
 * balance first for payroll-sourced loans).
 * BUSINESS loans (MBM-312): disburses directly on approval — debits the
 * source expense account, credits the recipient business's primary expense
 * account, moves PENDING_APPROVAL → ACTIVE. No contract-signing step.
 */
export async function POST(
  request: NextRequest,
  { params }: { params: { loanId: string } }
) {
  try {
    const user = await getServerUser()
    if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

    const permissions = getEffectivePermissions(user)
    if (!permissions.canManageLending && user.role !== 'admin') {
      return NextResponse.json({ error: 'Permission denied — canManageLending required' }, { status: 403 })
    }

    const loan = await prisma.accountOutgoingLoans.findUnique({
      where: { id: params.loanId },
      include: {
        payrollAccount: { select: { id: true, balance: true } },
        recipientEmployee: { select: { id: true, phone: true } },
        expenseAccount: { select: { id: true, balance: true, accountName: true } },
        recipientBusiness: { select: { id: true, name: true } },
        creator: { select: { id: true } },
      },
    })

    if (!loan) return NextResponse.json({ error: 'Loan not found' }, { status: 404 })
    if (loan.status !== 'PENDING_APPROVAL') {
      return NextResponse.json({ error: `Cannot approve loan in status: ${loan.status}` }, { status: 400 })
    }

    // Find the approver's employee record if they have one
    const employeeRecord = await prisma.employees.findFirst({
      where: { userId: user.id },
      select: { id: true },
    })

    if (loan.loanType === 'BUSINESS') {
      // MBM-312: disburse now — debit source, credit the recipient
      // business's primary expense account, move straight to ACTIVE.
      if (!loan.expenseAccountId || !loan.recipientBusinessId) {
        return NextResponse.json({ error: 'Loan is missing its source account or recipient business' }, { status: 400 })
      }
      const sourceBalance = Number(loan.expenseAccount?.balance ?? 0)
      const loanAmount = Number(loan.principalAmount)
      if (sourceBalance < loanAmount) {
        return NextResponse.json({
          error: `Insufficient balance. Account balance: $${sourceBalance.toFixed(2)}`,
        }, { status: 400 })
      }

      const updated = await prisma.$transaction(async (tx: any) => {
        const payment = await tx.expenseAccountPayments.create({
          data: {
            expenseAccountId: loan.expenseAccountId!,
            payeeType: 'BUSINESS',
            payeeBusinessId: loan.recipientBusinessId,
            amount: loanAmount,
            paymentDate: new Date(),
            notes: `🤝 Loan disbursement — ${loan.purpose ?? 'No purpose specified'}`,
            isFullPayment: true,
            status: 'SUBMITTED',
            paymentType: 'LOAN_DISBURSEMENT',
            outgoingLoanId: loan.id,
            createdBy: user.id,
          },
        })

        await tx.expenseAccounts.update({
          where: { id: loan.expenseAccountId! },
          data: { balance: { decrement: loanAmount } },
        })

        const recipientAccount = await tx.expenseAccounts.findFirst({
          where: { businessId: loan.recipientBusinessId!, isActive: true, isSibling: false },
          orderBy: { createdAt: 'asc' },
          select: { id: true },
        })
        if (recipientAccount) {
          await tx.expenseAccountDeposits.create({
            data: {
              expenseAccountId: recipientAccount.id,
              sourceType: 'LOAN_RECEIVED',
              sourceOutgoingLoanId: loan.id,
              amount: loanAmount,
              depositDate: new Date(),
              autoGeneratedNote: `🤝 Loan received — ${loan.purpose ?? loan.loanNumber}`,
              createdBy: user.id,
            },
          })
          await tx.expenseAccounts.update({
            where: { id: recipientAccount.id },
            data: { balance: { increment: loanAmount } },
          })
        }

        return tx.accountOutgoingLoans.update({
          where: { id: loan.id },
          data: {
            status: 'ACTIVE',
            approvedByEmployeeId: employeeRecord?.id ?? null,
            approvedAt: new Date(),
            disbursementPaymentId: payment.id,
          },
        })
      })

      try {
        await emitNotification({
          userIds: [loan.createdBy],
          type: 'LOAN_REQUEST_APPROVED',
          title: 'Loan request approved',
          message: `${loan.loanNumber} — $${loanAmount.toFixed(2)} to ${loan.recipientBusiness?.name ?? 'business'} has been disbursed`,
          linkUrl: `/expense-accounts/${loan.expenseAccountId}`,
          metadata: { loanId: loan.id, loanNumber: loan.loanNumber },
        })
      } catch { /* non-critical */ }

      return NextResponse.json({
        success: true,
        data: { loan: { id: updated.id, status: updated.status } },
      })
    }

    // EMPLOYEE loans: require borrower phone number on file before approval
    const borrowerPhone = (loan as any).recipientEmployee?.phone
    if (!borrowerPhone) {
      return NextResponse.json({
        error: 'Cannot approve — borrower has no phone number on file. Update the employee record first.',
      }, { status: 400 })
    }

    // For EMPLOYEE loans sourced from payroll account: check payroll balance
    if (loan.payrollAccountId && loan.payrollAccount) {
      const payrollBalance = Number(loan.payrollAccount.balance)
      const loanAmount = Number(loan.principalAmount)
      if (payrollBalance < loanAmount) {
        const shortBy = (loanAmount - payrollBalance).toFixed(2)
        return NextResponse.json({
          error: `Insufficient payroll balance — fund payroll first (short by $${shortBy})`,
        }, { status: 400 })
      }
    }

    const updated = await prisma.accountOutgoingLoans.update({
      where: { id: params.loanId },
      data: {
        status: 'PENDING_CONTRACT',
        approvedByEmployeeId: employeeRecord?.id ?? null,
        approvedAt: new Date(),
      },
    })

    return NextResponse.json({
      success: true,
      data: { loan: { id: updated.id, status: updated.status } },
    })
  } catch (error) {
    console.error('Error approving loan:', error)
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 })
  }
}
