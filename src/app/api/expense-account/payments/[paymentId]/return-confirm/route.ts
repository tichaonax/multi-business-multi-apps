import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'
import { getServerUser } from '@/lib/get-server-user'
import { isAccountCashier } from '@/lib/expense-account/receipt-review-access'
import { updateExpenseAccountBalanceTx } from '@/lib/expense-account-utils'
import { emitNotification, clearGroupedNotifications } from '@/lib/notifications/notification-emitter'
import { returnConfirmGroupKey } from '@/lib/expense-account/payment-return'

/**
 * POST /api/expense-account/payments/[paymentId]/return-confirm
 * Cashier (or admin) confirms physical/electronic receipt of the funds the
 * requester reported returning. Credits the amount back to the expense
 * account via a deposit, and locks the expense read-only. Guarded against
 * duplicate confirmation — only fires once per return request.
 */
export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ paymentId: string }> }
) {
  try {
    const user = await getServerUser()
    if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

    const { paymentId } = await params

    const payment = await prisma.expenseAccountPayments.findUnique({
      where: { id: paymentId },
      select: {
        id: true,
        expenseAccountId: true,
        locked: true,
        returnRequestedAmount: true,
        returnRequestedAt: true,
        returnRequestedBy: true,
        returnConfirmedAt: true,
        notes: true,
      },
    })
    if (!payment) return NextResponse.json({ error: 'Payment not found' }, { status: 404 })

    const isAdmin = user.role === 'admin'
    const isCashier = isAdmin || await isAccountCashier(user.id, isAdmin, payment.expenseAccountId)
    if (!isCashier) {
      return NextResponse.json({ error: 'Only a cashier or admin can confirm this return' }, { status: 403 })
    }

    if (payment.locked || payment.returnConfirmedAt) {
      return NextResponse.json({ error: 'This return has already been confirmed' }, { status: 400 })
    }
    if (!payment.returnRequestedAt || payment.returnRequestedAmount == null) {
      return NextResponse.json({ error: 'No pending return request for this expense' }, { status: 400 })
    }

    const amount = Number(payment.returnRequestedAmount)
    const now = new Date()

    await prisma.$transaction(async (tx) => {
      await tx.expenseAccountDeposits.create({
        data: {
          expenseAccountId: payment.expenseAccountId,
          sourceType: 'PAYMENT_RETURN',
          sourcePaymentId: payment.id,
          amount,
          depositDate: now,
          autoGeneratedNote: `Unused funds returned: ${payment.notes || `payment ${payment.id.slice(0, 8)}`} (confirmed by ${user.name})`,
          createdBy: payment.returnRequestedBy ?? user.id,
        },
      })
      await updateExpenseAccountBalanceTx(tx, payment.expenseAccountId)
      await tx.expenseAccountPayments.update({
        where: { id: payment.id },
        data: {
          returnConfirmedAt: now,
          returnConfirmedBy: user.id,
          locked: true,
        },
      })
    })

    await clearGroupedNotifications(returnConfirmGroupKey(paymentId))

    if (payment.returnRequestedBy) {
      await emitNotification({
        userIds: [payment.returnRequestedBy],
        type: 'PAYMENT_RETURN_CONFIRMED',
        title: 'Return confirmed',
        message: `${user.name} confirmed receipt of $${amount.toFixed(2)} returned for "${payment.notes || `payment ${payment.id.slice(0, 8)}`}". The expense is now read-only.`,
        linkUrl: `/expense-accounts/${payment.expenseAccountId}?tab=transactions&openReceiptsForPayment=${paymentId}`,
        metadata: { paymentId, accountId: payment.expenseAccountId, amount },
      })
    }

    return NextResponse.json({ success: true, data: { amount } })
  } catch (error) {
    console.error('Error confirming return:', error)
    return NextResponse.json({ error: 'Failed to confirm return' }, { status: 500 })
  }
}
