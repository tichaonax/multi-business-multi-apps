'use client'

import { useState, useEffect } from 'react'
import { RequestRepaymentModal } from './request-repayment-modal'

interface DepositDetail {
  id: string
  amount: number
  depositDate: string
  sourceType: string
  autoGeneratedNote: string | null
  autoTransferSource: string | null
  manualNote: string | null
  transactionType: string | null
  sourceBusiness: { id: string; name: string; type: string } | null
  createdBy: { id: string; name: string; email: string } | null
  // Transfer link
  sourceTransferPaymentId: string | null
  sourceTransferAccountId: string | null
  // Combo settle link
  comboRequestId: string | null
  // Return-unused-funds link (MBM-308)
  sourcePaymentId: string | null
  // Loan link (MBM-312) — set for LOAN_RECEIVED / LOAN_REPAYMENT
  loan: {
    id: string
    loanNumber: string
    status: string
    principalAmount: number
    remainingBalance: number
    sourceAccountId: string | null
    sourceAccountName: string | null
    recipientBusinessId: string | null
    pendingRepaymentAmount: number
    pendingRepaymentCount: number
  } | null
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex gap-3">
      <span className="text-xs text-gray-400 w-28 shrink-0 pt-0.5">{label}</span>
      <span className="text-sm text-primary break-words">{value}</span>
    </div>
  )
}

function sourceTypeLabel(sourceType: string): string {
  switch (sourceType) {
    case 'CASH': return '💵 Cash'
    case 'BANK_TRANSFER': return '🏦 Bank Transfer'
    case 'ACCOUNT_TRANSFER': return '↩ Account Transfer'
    case 'BUSINESS': return '🏢 Business Funding'
    case 'LOAN_RECEIVED': return '🤝 Loan Received'
    case 'LOAN_REPAYMENT': return '🔄 Loan Repayment'
    case 'PAYROLL_FUNDING': return '💼 Payroll Funding'
    case 'TRANSFER_RETURN': return '↩️ Transfer Return'
    case 'PETTY_CASH': return '🪙 Petty Cash'
    case 'WIFI_TOKEN_SALE': return '📡 WiFi Portal Sale'
    case 'R710_TOKEN_SALE': return '📶 R710 WiFi Sale'
    case 'COMBO_SETTLE': return '🧾 Combo Settlement Return'
    case 'PAYMENT_RETURN': return '💰 Payment Return'
    default: return sourceType.charAt(0) + sourceType.slice(1).toLowerCase().replace(/_/g, ' ')
  }
}

export function DepositDetailModal({
  isOpen,
  onClose,
  accountId,
  depositId,
}: {
  isOpen: boolean
  onClose: () => void
  accountId: string
  depositId: string
}) {
  const [deposit, setDeposit] = useState<DepositDetail | null>(null)
  const [loading, setLoading] = useState(false)
  const [showRepaymentRequest, setShowRepaymentRequest] = useState(false)

  const loadDeposit = () => {
    if (!accountId || !depositId) return
    fetch(`/api/expense-account/${accountId}/deposits/${depositId}`, { credentials: 'include' })
      .then(r => r.ok ? r.json() : null)
      .then(d => setDeposit(d?.data?.deposit ?? null))
      .catch(() => {})
  }

  useEffect(() => {
    if (!isOpen || !accountId || !depositId) { setDeposit(null); return }
    setLoading(true)
    fetch(`/api/expense-account/${accountId}/deposits/${depositId}`, { credentials: 'include' })
      .then(r => r.ok ? r.json() : null)
      .then(d => setDeposit(d?.data?.deposit ?? null))
      .catch(() => {})
      .finally(() => setLoading(false))
  }, [isOpen, accountId, depositId])

  if (!isOpen) return null

  const isAutoXferIn = deposit?.sourceType === 'ACCOUNT_TRANSFER'
  const isComboSettle = deposit?.sourceType === 'COMBO_SETTLE'
  const isPaymentReturn = deposit?.sourceType === 'PAYMENT_RETURN'
  const isLoanReceived = deposit?.sourceType === 'LOAN_RECEIVED'
  const isLoanRepayment = deposit?.sourceType === 'LOAN_REPAYMENT'
  const note = deposit?.manualNote || deposit?.autoGeneratedNote || null

  return (
    <div
      className="fixed inset-0 bg-black/60 backdrop-blur-sm flex items-center justify-center z-[10200] p-4"
      onClick={onClose}
    >
      <div
        className="bg-white dark:bg-gray-900 rounded-xl shadow-2xl border border-border w-full max-w-sm"
        onClick={e => e.stopPropagation()}
      >
        {/* Header */}
        <div className="flex items-center justify-between px-5 py-4 border-b border-border">
          <h3 className="text-base font-semibold text-primary">
            {isAutoXferIn ? '↩ Auto-Transfer In' : '📥 Deposit Details'}
          </h3>
          <button
            onClick={onClose}
            className="text-gray-400 hover:text-gray-600 dark:hover:text-gray-200 text-2xl leading-none w-7 h-7 flex items-center justify-center rounded hover:bg-gray-100 dark:hover:bg-gray-800"
          >
            &times;
          </button>
        </div>

        {/* Body */}
        <div className="px-5 py-4">
          {loading ? (
            <p className="text-sm text-gray-400 py-8 text-center">Loading…</p>
          ) : !deposit ? (
            <p className="text-sm text-gray-400 py-8 text-center">Deposit not found</p>
          ) : (
            <div className="space-y-3">
              <Row label="Amount" value={`$${deposit.amount.toFixed(2)}`} />
              <Row label="Date" value={deposit.depositDate.slice(0, 10)} />
              <Row label="Source" value={sourceTypeLabel(deposit.sourceType)} />

              {/* Auto-transfer: show source account with link */}
              {isAutoXferIn && deposit.autoTransferSource && (
                <div className="flex gap-3">
                  <span className="text-xs text-gray-400 w-28 shrink-0 pt-0.5">From Account</span>
                  {deposit.sourceTransferAccountId && deposit.sourceTransferPaymentId ? (
                    <a
                      href={`/expense-accounts/${deposit.sourceTransferAccountId}/payments/${deposit.sourceTransferPaymentId}`}
                      className="text-sm text-sky-600 dark:text-sky-400 hover:underline font-medium"
                      onClick={onClose}
                    >
                      ↩ {deposit.autoTransferSource}
                    </a>
                  ) : (
                    <span className="text-sm text-sky-700 dark:text-sky-400 font-medium">
                      ↩ {deposit.autoTransferSource}
                    </span>
                  )}
                </div>
              )}

              {/* Non-auto-transfer: show source business if present */}
              {!isAutoXferIn && deposit.sourceBusiness && (
                <Row label="From Business" value={deposit.sourceBusiness.name} />
              )}

              {/* MBM-312: real loan details instead of just the generic
                  "Loan Received"/"Loan Repayment" source label above. */}
              {deposit.loan && (
                <>
                  <Row label="Loan #" value={deposit.loan.loanNumber} />
                  <Row label={isLoanReceived ? 'Source Account' : 'Lending Account'} value={deposit.loan.sourceAccountName ?? 'Unknown'} />
                  <Row label="Loan Status" value={deposit.loan.status.replace(/_/g, ' ')} />
                  <Row label="Outstanding Balance" value={`$${deposit.loan.remainingBalance.toFixed(2)} of $${deposit.loan.principalAmount.toFixed(2)}`} />
                  {deposit.loan.pendingRepaymentCount > 0 && (
                    <Row
                      label="Pending Request"
                      value={`$${deposit.loan.pendingRepaymentAmount.toFixed(2)} awaiting cashier approval${deposit.loan.pendingRepaymentCount > 1 ? ` (${deposit.loan.pendingRepaymentCount} requests)` : ''}`}
                    />
                  )}
                </>
              )}

              {note && <Row label="Notes" value={note} />}
              {deposit.transactionType && deposit.transactionType !== 'STANDARD' && (
                <Row label="Type" value={deposit.transactionType} />
              )}
              {deposit.createdBy && <Row label="Recorded by" value={deposit.createdBy.name} />}
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="px-5 py-3 border-t border-border flex justify-between items-center">
          {deposit && isComboSettle && deposit.comboRequestId ? (
            <a
              href={`/expense-accounts/${accountId}/combo-requests/${deposit.comboRequestId}`}
              onClick={onClose}
              className="text-xs text-purple-600 dark:text-purple-400 hover:underline"
            >
              View Combo Request →
            </a>
          ) : deposit && isPaymentReturn && deposit.sourcePaymentId ? (
            <a
              href={`/expense-accounts/${accountId}?tab=transactions&openPaymentDetail=${deposit.sourcePaymentId}`}
              onClick={onClose}
              className="text-xs text-purple-600 dark:text-purple-400 hover:underline"
            >
              View Original Expense →
            </a>
          ) : deposit && !isAutoXferIn ? (
            <a
              href={`/expense-accounts/${accountId}/deposits/${depositId}`}
              onClick={onClose}
              className="text-xs text-blue-600 dark:text-blue-400 hover:underline"
            >
              View full details →
            </a>
          ) : null}
          {/* MBM-312: initiate a repayment request directly from here —
              same cashier-approval flow as the Loans Owed tab, just
              reachable without navigating away first. */}
          {deposit?.loan && isLoanReceived && deposit.loan.status === 'ACTIVE' && (
            deposit.loan.pendingRepaymentCount > 0 ? (
              <span
                title="A repayment request for this loan is already awaiting cashier approval"
                className="px-3 py-1.5 text-xs font-medium text-amber-700 dark:text-amber-400 bg-amber-50 dark:bg-amber-900/20 border border-amber-200 dark:border-amber-700 rounded-md"
              >
                Request Pending
              </span>
            ) : (
              <button
                onClick={() => setShowRepaymentRequest(true)}
                className="px-3 py-1.5 text-xs font-medium text-green-700 dark:text-green-300 bg-green-50 dark:bg-green-900/20 border border-green-200 dark:border-green-700 rounded-md hover:bg-green-100 transition-colors"
              >
                Request Repayment
              </button>
            )
          )}
          <button
            onClick={onClose}
            className="ml-auto px-4 py-1.5 text-sm bg-gray-100 dark:bg-gray-800 hover:bg-gray-200 dark:hover:bg-gray-700 text-primary rounded-md"
          >
            Close
          </button>
        </div>
      </div>

      {showRepaymentRequest && deposit?.loan && (
        /* Stop clicks from bubbling to the DepositDetailModal backdrop's
           onClick={onClose} above — without this, any click inside
           RequestRepaymentModal (itself a sibling, not a descendant of the
           stopPropagation'd card) closes this whole modal instead. */
        <div onClick={e => e.stopPropagation()}>
          <RequestRepaymentModal
            loanId={deposit.loan.id}
            loanNumber={deposit.loan.loanNumber}
            contextLabel={`owed to ${deposit.loan.sourceAccountName ?? 'the lending account'}`}
            remainingBalance={deposit.loan.remainingBalance}
            onSuccess={() => { setShowRepaymentRequest(false); loadDeposit() }}
            onClose={() => setShowRepaymentRequest(false)}
          />
        </div>
      )}
    </div>
  )
}
